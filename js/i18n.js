// Read from localStorage or default to 'tr'
let currentLanguage = localStorage.getItem('bilesim_lang') || 'tr';

function translatePage(lang) {
    currentLanguage = lang;
    localStorage.setItem('bilesim_lang', lang);
    
    // Set direction for Arabic
    if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.documentElement.style.fontFamily = "'Plus Jakarta Sans', sans-serif, 'Arabic Typesetting', Arial"; // fallback for arabic
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.documentElement.style.fontFamily = "'Plus Jakarta Sans', sans-serif";
    }

    document.documentElement.setAttribute('lang', lang);

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update active state in dropdown
    const btn = document.getElementById('langBtn');
    if (btn) {
        const flagMap = { 'tr': 'tr', 'en': 'gb', 'ar': 'sa', 'ru': 'ru' };
        btn.innerHTML = `<span class="fi fi-${flagMap[lang]}"></span> ` + lang.toUpperCase() + ' <i class="ph ph-caret-down"></i>';
    }
}

document.addEventListener('DOMContentLoaded', () => {
    // Initial translation setup
    translatePage(currentLanguage);

    // Language switcher toggle
    const langBtn = document.getElementById('langBtn');
    const langSwitcher = document.querySelector('.lang-switcher');
    
    if (langBtn && langSwitcher) {
        langBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            langSwitcher.classList.toggle('active');
        });

        // Click outside closes dropdown
        document.addEventListener('click', () => {
            langSwitcher.classList.remove('active');
        });

        // Language items click
        const langItems = document.querySelectorAll('.lang-dropdown li');
        langItems.forEach(item => {
            item.addEventListener('click', (e) => {
                const selectedLang = e.target.getAttribute('data-lang');
                translatePage(selectedLang);
                langSwitcher.classList.remove('active');
            });
        });
    }
});
